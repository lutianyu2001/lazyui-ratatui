/// Whether terminals can't be trusted to agree with Ratatui on `c`.
pub(crate) fn unsteady(c: char) -> bool {
    let c = u32::from(c);
    UNSTEADY
        .binary_search_by(|&(low, high)| {
            if high < c {
                std::cmp::Ordering::Less
            } else if low > c {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_in_order() {
        assert!(UNSTEADY.iter().all(|(low, high)| low <= high));
        assert!(UNSTEADY.windows(2).all(|pair| pair[0].1 < pair[1].0));
    }

    #[test]
    fn the_table_finds_both_ends_of_a_range() {
        for c in ['\u{1f1e6}', '\u{1f1ff}', '\u{fe0f}', '\u{fff9}'] {
            assert!(unsteady(c), "{c:?}");
        }
        for c in ['a', '文', '\u{301}', '\u{fffd}', '\u{1f600}'] {
            assert!(!unsteady(c), "{c:?}");
        }
    }
}
